import { NextResponse } from 'next/server';
import type { NextRequest } from 'next/server';
import { getToken } from 'next-auth/jwt';

const CSP =
  process.env.NODE_ENV === 'production'
    ? "script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data: blob:; connect-src 'self'; worker-src 'self'; frame-ancestors 'none';"
    : // Development: Next.js React Refresh / HMR evaluates strings at runtime and
      // requires 'unsafe-eval'. Without it the dev runtime throws EvalError and
      // client interactivity (login submit, etc.) silently dies.
      "script-src 'self' 'unsafe-inline' 'unsafe-eval'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data: blob:; connect-src 'self' ws:; worker-src 'self' blob:; frame-ancestors 'none';";

// Paths that should NOT get CSP headers (SW assets, APIs, static files)
const CSP_EXEMPT = [
  '/sw.js',
  '/manifest.json',
  '/api/',
  '/_next/',
  '/workbox-',
  '/fallback-',
  '/icons/',
  '/images/',
];

/**
 * Development-only service worker.
 *
 * `public/sw.js` is generated by the production build and stays on disk after
 * it, so a browser that once ran the production build on this origin keeps a
 * registered worker. next-pwa is disabled in development, so nothing replaces
 * it - and the old worker happily caches the DEV server's chunk URLs.
 *
 * Dev chunk URLs are NOT content-hashed (`/_next/static/chunks/main-app.js`),
 * so their content changes on every recompile while the URL stays the same.
 * The worker then serves the PREVIOUS compile's bundle: the page runs a mix of
 * old and new React code and React fails with
 * "Rendered more hooks than during the previous render".
 *
 * This worker deletes itself and every cache the production worker left
 * behind, then reloads the open tabs. In production the real /sw.js is served.
 */
const DEV_SERVICE_WORKER = `/* development-only: removes the stale production worker */
self.addEventListener('install', () => { self.skipWaiting(); });
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    try { await self.registration.unregister(); } catch (_) {}
    try {
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));
    } catch (_) {}
    try {
      const clients = await self.clients.matchAll({ type: 'window' });
      for (const client of clients) {
        try { client.postMessage({ type: 'SARI_SW_DISABLED' }); } catch (_) {}
        try { await client.navigate(client.url); } catch (_) {}
      }
    } catch (_) {}
  })());
});
`;

function isCspExempt(pathname: string): boolean {
  return CSP_EXEMPT.some((p) => pathname === p || pathname.startsWith(p));
}

export async function middleware(request: NextRequest) {
  const pathname = request.nextUrl.pathname;

  // Development: never let the production service worker control the dev
  // server. See DEV_SERVICE_WORKER above for why a stale worker breaks the
  // dev bundle. The worker uninstalls itself and purges the caches.
  if (pathname === '/sw.js' && process.env.NODE_ENV !== 'production') {
    return new NextResponse(DEV_SERVICE_WORKER, {
      status: 200,
      headers: {
        'Content-Type': 'application/javascript; charset=utf-8',
        'Cache-Control': 'no-store, no-cache, must-revalidate',
        'Service-Worker-Allowed': '/',
      },
    });
  }

  // Always let SW assets, icons, manifest, and offline page through without auth
  if (
    pathname === '/sw.js' ||
    pathname === '/manifest.json' ||
    pathname.startsWith('/workbox-') ||
    pathname.startsWith('/fallback-') ||
    pathname.startsWith('/icons/') ||
    pathname === '/offline' ||
    pathname === '/login' ||
    pathname === '/forgot-password'
  ) {
    const response = NextResponse.next();
    if (!isCspExempt(pathname)) {
      response.headers.set('Content-Security-Policy', CSP);
    }
    return response;
  }

  const token = await getToken({ req: request, secret: process.env.NEXTAUTH_SECRET });

  if (!token) {
    const loginUrl = new URL('/login', request.url);
    loginUrl.searchParams.set('callbackUrl', request.url);
    return NextResponse.redirect(loginUrl);
  }

  // Revoked marker stamped by the auth JWT callback when the live user row is
  // deactivated/missing (see lib/server/auth.ts) — bounce before rendering.
  if (token.role === 'revoked') {
    const loginUrl = new URL('/login', request.url);
    loginUrl.searchParams.set('callbackUrl', request.url);
    return NextResponse.redirect(loginUrl);
  }

  const response = NextResponse.next();

  // Set CSP on page responses only (skip APIs, SW, static assets)
  if (!isCspExempt(pathname)) {
    response.headers.set('Content-Security-Policy', CSP);
  }

  return response;
}

